#!/usr/bin/env python3
"""Generate Spark, MySQL, PostgreSQL and ClickHouse DDL from the field contract."""
from __future__ import annotations

import argparse
import csv
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TYPES = {
    'spark': {'STRING': 'STRING', 'LONG': 'BIGINT', 'INTEGER': 'INT', 'DOUBLE': 'DOUBLE', 'BOOLEAN': 'BOOLEAN', 'DATE': 'DATE', 'TIMESTAMP': 'TIMESTAMP'},
    'mysql': {'STRING': 'TEXT', 'LONG': 'BIGINT', 'INTEGER': 'INT', 'DOUBLE': 'DOUBLE', 'BOOLEAN': 'BOOLEAN', 'DATE': 'DATE', 'TIMESTAMP': 'DATETIME'},
    'postgres': {'STRING': 'TEXT', 'LONG': 'BIGINT', 'INTEGER': 'INTEGER', 'DOUBLE': 'DOUBLE PRECISION', 'BOOLEAN': 'BOOLEAN', 'DATE': 'DATE', 'TIMESTAMP': 'TIMESTAMP'},
    'clickhouse': {'STRING': 'String', 'LONG': 'Int64', 'INTEGER': 'Int32', 'DOUBLE': 'Float64', 'BOOLEAN': 'Bool', 'DATE': 'Date', 'TIMESTAMP': "DateTime('Asia/Shanghai')"},
}


def read_contract(path=ROOT / '清单/字段契约.csv'):
    tables = defaultdict(list)
    with Path(path).open(encoding='utf-8-sig') as stream:
        for field in csv.DictReader(stream):
            tables[field['表名']].append(field)
    if len(tables) != 55 or sum(map(len, tables.values())) != 866:
        raise ValueError('Incomplete 55-table / 866-column field contract')
    return dict(tables)


def identifier(value, dialect):
    quote = '"' if dialect == 'postgres' else '`'
    return quote+value.replace(quote, quote*2)+quote


def literal(value):
    return "'"+value.replace("'", "''")+"'"


def sql_type(source, dialect, nullable=True):
    decimal = re.fullmatch(r'DECIMAL\((\d+),(\d+)\)', source)
    if decimal:
        precision, scale = decimal.groups()
        result = f'Decimal({precision},{scale})' if dialect == 'clickhouse' else f'DECIMAL({precision},{scale})'
    else:
        result = TYPES[dialect][source]
    if dialect == 'clickhouse' and nullable:
        return 'Nullable('+result+')'
    return result


def generate(dialect, naming='zh', tables=None):
    tables = read_contract() if tables is None else tables
    blocks = ['-- Generated by tools/build_ddl.py; edit the field contract sources and regenerate.', '-- naming='+naming+'; simulated reference schema; grain is validated by tests, not enforced as a database primary key.']
    if dialect == 'spark' and naming == 'zh':
        blocks.append('-- Spark 3.4 SessionCatalog rejects Chinese persistent table names, including quoted names.\n-- Generate executable English DDL: python tools/build_ddl.py --naming en --out work/ddl-en\n-- Quoted Chinese temporary views remain supported for the documented ETL.')
    for table in sorted(tables):
        fields = tables[table]
        table_name = table if naming == 'zh' else fields[0]['表英文名']
        quoted_table = identifier(table_name, dialect)
        keys = sorted((f for f in fields if f['粒度键序号']), key=lambda f: int(f['粒度键序号']))
        columns, comments = [], []
        for field in fields:
            name = field['字段名'] if naming == 'zh' else field['字段英文名']
            quoted_name = identifier(name, dialect)
            line = '  '+quoted_name+' '+sql_type(field['类型'], dialect, field['可空']=='是')
            if dialect != 'clickhouse' and field['可空']=='否':
                line += ' NOT NULL'
            comment = field['字段名']+'：'+field['字段说明']
            if dialect == 'postgres':
                comments.append('COMMENT ON COLUMN '+quoted_table+'.'+quoted_name+' IS '+literal(comment)+';')
            else:
                line += ' COMMENT '+literal(comment)
            columns.append(line)
        grain = ', '.join(f['字段名'] for f in keys)
        body = '-- '+table+'; grain: '+grain+'\nCREATE TABLE '+quoted_table+' (\n'+',\n'.join(columns)+'\n)'
        if dialect == 'spark':
            body += ' USING PARQUET'
        elif dialect == 'mysql':
            body += ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci'
        elif dialect == 'clickhouse':
            order = ', '.join(identifier(f['字段名'] if naming == 'zh' else f['字段英文名'], dialect) for f in keys)
            body += '\nENGINE = MergeTree\nORDER BY ('+order+')'
            if any(f['可空']=='是' for f in keys):
                body += '\nSETTINGS allow_nullable_key = 1'
        blocks.append(body+';'+('\n'+'\n'.join(comments) if comments else ''))
    return '\n\n'.join(blocks)+'\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--naming', choices=('zh', 'en'), default='zh')
    parser.add_argument('--out', type=Path, default=ROOT / 'DDL')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = {d+'.sql': generate(d, args.naming) for d in TYPES}
    drift = []
    for name, content in outputs.items():
        path = args.out / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                drift.append(name)
        else:
            args.out.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if drift:
        print('Generated DDL drift: '+', '.join(drift), file=sys.stderr)
        return 1
    print(('Verified' if args.check else 'Generated')+' '+args.naming+' DDL: '+', '.join(outputs))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
